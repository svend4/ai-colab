"""reconcile.py — детектор коллизий и план их НЕразрушающего разрешения.

Операционализирует docs/nondestructive-reconciliation-2026-07-06.md (принцип `reconcile`,
ратифицирован в оркестраторном цикле). Формула принципа: КОЛЛИЗИЯ НИКОГДА НЕ РЕШАЕТСЯ
УДАЛЕНИЕМ — она решается ветвлением в новый адресуемый артефакт + указателем старшинства.
Старое остаётся живым; удаление содержания — единственный исход, требующий человека.

Уникальная ниша (НЕ дублирует существующие детекторы):
  · gap_scan.py       — разрывы «замысел↔реальность» (orphan-код, дрейф деривата, висячие ссылки);
  · topic_sanitation  — залежавшиеся темы;
  · status_drift / reconcile_state.py — дрейф STATUS / сверка primary↔производные снимки.
reconcile.py ловит именно КОЛЛИЗИИ артефактов (классы §3 доки) и печатает план исхода из §4.

Классы коллизий (из §3 доки), которые ловит этот детектор:
  B  ДУБЛЬ / near-duplicate — пары .md с высоким совпадением содержания на РАЗНЫХ путях
                              (нормализованные строки: Jaccard > 0.6 ИЛИ containment > 0.7).
  E  ПЕРЕПОЛНЕНИЕ          — файл канона (.md) больше порога (60 КБ): dialog.md и т.п.
  C  ДИВЕРГЕНЦИЯ           — кластер файлов с общей темой в имени (orchestrat / closed-loop /
                              cauldron / reconcile) — кандидаты вариантов одной сущности.

Команды:
  python tools/reconcile.py detect [--json]   # просканировать и найти коллизии по классам B/E/C
  python tools/reconcile.py plan   [--json]   # по каждой коллизии — предложенный НЕразрушающий исход
                                              #   (§4: primary+cross-link / snapshot / variant),
                                              #   с пометкой что требует ЧЕЛОВЕКА. dry-run, ничего не пишет.

Инварианты (жёстко):
  · НЕТ команды/ветки, которая удаляет / перемещает / правит файлы — ТОЛЬКО чтение и печать.
  · dry-run по определению: `plan` печатает предложение, но НИЧЕГО не применяет.
  · Флип primary между конкурентами и любое `drop` — НИКОГДА автоматически, всегда человек (§5, §10 доки).

Коды выхода (advisory, как gap_scan --strict):
  0 — коллизий не найдено (чистый отчёт);
  1 — найдены коллизии, требующие внимания человека;
  2 — ошибка использования.
"""
import os
import sys
import re
import json
import glob
import hashlib
import itertools

from _ioutil import configure_output
from _cli import help_guard

configure_output()

_SELF_TOOLS = os.path.dirname(os.path.abspath(__file__))
ROOT = os.environ.get("COLLAB_ROOT") or os.path.dirname(_SELF_TOOLS)

# --- Пороги (совпадают с формулировками §3 задачи/доки; вынесены в константы для теста) ---
OVERFLOW_BYTES = 60 * 1024        # E: канон-файл больше 60 КБ — переполнение (dialog.md)
DUP_JACCARD = 0.6                 # B: порог Jaccard по нормализованным строкам
DUP_CONTAINMENT = 0.7            # B: порог вложенности (младший почти целиком в старшем)
MIN_MEANINGFUL_LEN = 12          # строку короче игнорируем как «шумовую» при сравнении содержания
MIN_SHARED_LINES = 4             # B: минимум ОБЩИХ значимых строк — иначе это не «near-duplicate
                                 #    документ», а совпадение одной-двух boilerplate-строк (напр.
                                 #    повторённая строка в двух генератах даёт containment=1.0 на 1 строке).

# Каталоги, где живёт канон/отчёты/материалы котла — здесь ищем коллизии.
SCAN_DIRS = ("docs", "reports", "kotel", "topics")

# Известные ТЕМЫ дивергенции (класс C) из §9 доки: несколько документов вокруг одной сущности.
# Узкий курируемый список (не любое слово), чтобы C не фонил на общей лексике.
DIVERGENCE_THEMES = ("orchestrat", "closed-loop", "cauldron", "reconcil")

# Генерируемые артефакты, которые НЕ считаем «переполнением канона»: их не сворачивает человек,
# они переписываются деривативно (dcard_index — автосгенерирован; доски — генерятся из primary).
GENERATED_BASENAMES = {
    "TASKS.md", "STATUS.md", "board.md", "PIPELINE.md", "QUESTIONS.md", "DECISIONS.md",
    "dcard_index.md", "agenda-generated.md",
}
# Маркеры «этот файл сгенерирован» в шапке — тогда переполнение чинится регенерацией, не reconcile.
GENERATED_MARKERS = (
    "автосгенерир", "автоматически сгенерир", "сгенерирован автоматически",
    "auto-generated", "autogenerated", "generated by", "не редактируйте вручную",
    "do not edit",
)


# ------------------------------------------------------------------ утилиты чтения (только read)

def _read(path):
    """Прочитать файл в utf-8 (errors=replace). Только чтение — инструмент ничего не пишет."""
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            return f.read()
    except OSError:
        return ""


def _rel(path):
    return os.path.relpath(path, ROOT).replace("\\", "/")


def _scan_md():
    """Все .md в зонах сканирования + top-level *.md; worktree-копии исключены (чужие деревья)."""
    files = []
    for d in SCAN_DIRS:
        base = os.path.join(ROOT, d)
        for p in glob.glob(os.path.join(base, "**", "*.md"), recursive=True):
            files.append(p)
    for p in glob.glob(os.path.join(ROOT, "*.md")):
        files.append(p)
    out = []
    seen = set()
    for p in files:
        rp = _rel(p)
        # worktrees/ — рабочие деревья других агентов; .git — служебное; не наша зона
        if "/worktrees/" in rp or rp.startswith(".git/") or "/.git/" in rp:
            continue
        ap = os.path.abspath(p)
        if ap in seen or not os.path.isfile(p):
            continue
        seen.add(ap)
        out.append(p)
    return sorted(out)


def _is_generated(path):
    """Генерируемый ли файл (по имени или маркеру в шапке) — такой не считаем переполнением канона."""
    if os.path.basename(path) in GENERATED_BASENAMES:
        return True
    head = _read(path)[:600].lower()
    return any(m in head for m in GENERATED_MARKERS)


def _short_sha(path):
    """Content-address снимка переполнения: `<base>_full-<sha8>.md` (§6 доки). Только для ИМЕНИ в плане."""
    h = hashlib.sha1(_read(path).encode("utf-8", "replace")).hexdigest()
    return h[:8]


def _norm_lines(path):
    """Множество нормализованных «значимых» строк файла (для сравнения содержания класса B).

    Нормализация: схлопнуть пробелы, обрезать края, нижний регистр; выкинуть короткие/шумовые
    строки (разделители, отдельные символы). Сравнение по множеству строк — дешёвый и устойчивый
    шингл-суррогат: одинаковый текст на разных путях даёт высокое пересечение.
    """
    out = set()
    for ln in _read(path).splitlines():
        s = re.sub(r"\s+", " ", ln).strip().lower()
        if len(s) >= MIN_MEANINGFUL_LEN:
            out.add(s)
    return out


# ------------------------------------------------------------------ B: ДУБЛЬ / near-duplicate

def find_duplicates():
    """Пары .md на разных путях с высоким совпадением содержания (класс B §3).

    Метрики по множествам нормализованных строк:
      · Jaccard      = |A∩B| / |A∪B|  — общая схожесть;
      · containment  = |A∩B| / min(|A|,|B|) — «младший почти целиком лежит в старшем».
    Порог по ЛЮБОЙ из метрик (containment ловит «дубль + добавленный хвост», где Jaccard проседает).
    """
    # Генерируемые файлы из B исключаем: их совпадения — деривативный шум (общий шаблон/строки),
    # а не «дубль канона», требующий reconcile-исхода.
    files = [p for p in _scan_md() if not _is_generated(p)]
    sets = {}
    for p in files:
        s = _norm_lines(p)
        if s:
            sets[p] = s
    out = []
    for a, b in itertools.combinations(sorted(sets), 2):
        A, B = sets[a], sets[b]
        inter = len(A & B)
        # порог по абсолютному числу общих строк: одна-две общих boilerplate-строки — не дубль документа
        if inter < MIN_SHARED_LINES:
            continue
        union = len(A | B)
        jac = inter / union if union else 0.0
        cont = inter / min(len(A), len(B))
        if jac >= DUP_JACCARD or cont >= DUP_CONTAINMENT:
            # старший = больший по размеру (кандидат в primary; но флип — человек, §5)
            pa, pb = a, b
            if os.path.getsize(pb) > os.path.getsize(pa):
                pa, pb = pb, pa
            out.append({
                "kind": "B-duplicate",
                "primary_candidate": _rel(pa),
                "other": _rel(pb),
                "jaccard": round(jac, 3),
                "containment": round(cont, 3),
                "shared_lines": inter,
                "evidence": "совпадение содержания: Jaccard=%.3f, containment=%.3f (общих строк %d)"
                            % (jac, cont, inter),
                "why": "почти одинаковые артефакты на разных путях (класс B §3 reconcile)",
            })
    out.sort(key=lambda d: (-d["jaccard"], -d["containment"]))
    return out


# ------------------------------------------------------------------ E: ПЕРЕПОЛНЕНИЕ

def find_overflow():
    """Файлы канона (.md) больше порога OVERFLOW_BYTES (класс E §3). Генерируемые — исключены."""
    out = []
    for p in _scan_md():
        if _is_generated(p):
            continue
        try:
            sz = os.path.getsize(p)
        except OSError:
            continue
        if sz > OVERFLOW_BYTES:
            out.append({
                "kind": "E-overflow",
                "path": _rel(p),
                "size": sz,
                "size_kb": round(sz / 1024, 1),
                "threshold_kb": OVERFLOW_BYTES // 1024,
                "evidence": "размер %.1f КБ > порога %d КБ" % (sz / 1024, OVERFLOW_BYTES // 1024),
                "why": "файл слишком велик — риск потери навигации/конфликтов (класс E §3 reconcile)",
            })
    out.sort(key=lambda d: -d["size"])
    return out


# ------------------------------------------------------------------ C: ДИВЕРГЕНЦИЯ

def find_divergence():
    """Кластеры файлов с общей ТЕМОЙ в имени (класс C §3) — кандидаты вариантов одной сущности.

    Курируемый список тем (DIVERGENCE_THEMES) из §9 доки, чтобы не фонить на общей лексике.
    Кластер = >=2 файлов с одним ключом темы. Это ADVISORY-кандидат: разведение dup↔divergence
    и сам вердикт «варианты одного или разные вещи» — за человеком (разные исходы, §4/§10).
    """
    files = _scan_md()
    buckets = {}
    for p in files:
        b = os.path.basename(p).lower()
        for theme in DIVERGENCE_THEMES:
            if theme in b:
                buckets.setdefault(theme, []).append(_rel(p))
    out = []
    for theme in DIVERGENCE_THEMES:
        members = sorted(buckets.get(theme, []))
        if len(members) >= 2:
            out.append({
                "kind": "C-divergence",
                "theme": theme,
                "members": members,
                "count": len(members),
                "evidence": "%d файлов вокруг темы %r в имени" % (len(members), theme),
                "why": "несколько документов одной сущности — кандидаты в варианты (класс C §3 reconcile)",
            })
    out.sort(key=lambda d: -d["count"])
    return out


# ------------------------------------------------------------------ detect (агрегатор)

def detect():
    """Собрать коллизии по всем классам (B/E/C). Возвращает dict класс→список находок."""
    return {
        "B_duplicate": find_duplicates(),
        "E_overflow": find_overflow(),
        "C_divergence": find_divergence(),
    }


def _detect_total(res):
    return sum(len(v) for v in res.values())


# ------------------------------------------------------------------ plan (dry-run исходы §4)

def plan():
    """Для каждой найденной коллизии — предложенный НЕразрушающий исход (§4 доки).

    dry-run: НИЧЕГО не пишет, только печатает предложение и помечает, что требует человека.
    Механизмы исхода (все без rm, §4/§6 доки):
      B → primary + cross-link ЛИБО тело младшего в variants/ (флип primary — человек);
      E → снапшот-заморозка `<base>_full-<sha8>.md` + активный хвост ЛИБО папочный режим D-002 (стратегия — человек);
      C → оба как variant (variant_of), тела сохранены; синтез в решение — по эстафете/человеку.
    """
    res = detect()
    items = []

    for d in res["B_duplicate"]:
        base = os.path.splitext(os.path.basename(d["other"]))[0]
        items.append({
            "class": "B",
            "collision": "%s ↔ %s" % (d["primary_candidate"], d["other"]),
            "outcome": "primary + cross-link (спорно) ИЛИ superseded+redirect (бесспорно)",
            "mechanism": "тело младшего сохранить как вариант (напр. topics/<t>/variants/%s.md), "
                         "в старшем — cross-link; старый путь → redirect-заглушка (ссылки не рвутся)"
                         % base,
            "primary_candidate": d["primary_candidate"],
            "needs_human": "флип primary между конкурентами и любое candidate-drop — ТОЛЬКО человек (§5)",
            "evidence": d["evidence"],
        })

    for d in res["E_overflow"]:
        base = os.path.splitext(os.path.basename(d["path"]))[0]
        # sha8 считаем от реального содержимого — имя снапшота content-address (§6). Это только ИМЯ в плане.
        abspath = os.path.join(ROOT, d["path"])
        sha = _short_sha(abspath)
        items.append({
            "class": "E",
            "collision": "%s (%.1f КБ)" % (d["path"], d["size_kb"]),
            "outcome": "снапшот-заморозка + активный хвост ИЛИ папочный режим (D-002)",
            "mechanism": "старое → неизменяемый архив %s_full-%s.md (content-address), новый — активный хвост; "
                         "git-тег по D-026 перед любым переносом" % (base, sha),
            "needs_human": "ВЫБОР стратегии (снапшот vs папочный режим) и перенос канона — человек (§9)",
            "evidence": d["evidence"],
        })

    for d in res["C_divergence"]:
        items.append({
            "class": "C",
            "collision": "тема %r: %s" % (d["theme"], ", ".join(d["members"])),
            "outcome": "оба (все) как variant (variant_of), тела сохранены; при доказанном — синтез в решение (D-018)",
            "mechanism": "пометить variant_of у не-primary, primary = принятый по эстафете/провенансу; "
                         "streams/ + skeleton document-synthesis для схождения",
            "needs_human": "вердикт «варианты ОДНОГО или разные сущности» и выбор primary — человек (§4/§10)",
            "evidence": d["evidence"],
        })

    return items


# ------------------------------------------------------------------ печать (human)

def _print_detect_human(res):
    titles = {
        "B_duplicate": "B ДУБЛЬ / near-duplicate (совпадение содержания на разных путях)",
        "E_overflow": "E ПЕРЕПОЛНЕНИЕ (канон-файл > %d КБ)" % (OVERFLOW_BYTES // 1024),
        "C_divergence": "C ДИВЕРГЕНЦИЯ (кластер вокруг одной темы — кандидаты вариантов)",
    }
    print("=== RECONCILE DETECT — коллизии по принципу reconcile (advisory, без удаления) ===")
    for key in ("B_duplicate", "E_overflow", "C_divergence"):
        items = res[key]
        print("\n## %s — %d" % (titles[key], len(items)))
        for it in items:
            if key == "B_duplicate":
                print("  • %s  ↔  %s" % (it["primary_candidate"], it["other"]))
            elif key == "E_overflow":
                print("  • %s (%.1f КБ)" % (it["path"], it["size_kb"]))
            else:
                print("  • тема %r (%d): %s" % (it["theme"], it["count"], ", ".join(it["members"])))
            print("      %s" % it["evidence"])
    print("\nИТОГО коллизий: %d" % _detect_total(res))


def _print_plan_human(items):
    print("=== RECONCILE PLAN — предложенный НЕразрушающий исход (§4 доки; dry-run, ничего не пишет) ===")
    print("Формула: коллизия НИКОГДА не решается удалением — только ветвлением + указателем старшинства.\n")
    if not items:
        print("Коллизий не найдено — план пуст.")
        return
    for it in items:
        print("[%s] %s" % (it["class"], it["collision"]))
        print("    исход:    %s" % it["outcome"])
        print("    механизм: %s" % it["mechanism"])
        print("    ЧЕЛОВЕК:  %s" % it["needs_human"])
        print("")
    print("Всего предложений: %d. НИЧЕГО не применено (dry-run). Любое drop/флип primary — только человек."
          % len(items))


# ------------------------------------------------------------------ CLI

def main(argv):
    help_guard(__doc__, argv)
    argv = list(argv)
    as_json = "--json" in argv
    cmd = None
    for a in argv:
        if a in ("detect", "plan"):
            cmd = a
            break
    if cmd is None:
        sys.stderr.write("Использование: python tools/reconcile.py {detect|plan} [--json]\n"
                         "  detect — найти коллизии (B дубль / E переполнение / C дивергенция)\n"
                         "  plan   — предложить НЕразрушающий исход по §4 (dry-run)\n")
        return 2

    if cmd == "detect":
        res = detect()
        total = _detect_total(res)
        if as_json:
            print(json.dumps(res, ensure_ascii=False, indent=2))
        else:
            _print_detect_human(res)
        return 1 if total else 0

    # cmd == "plan"
    items = plan()
    if as_json:
        print(json.dumps(items, ensure_ascii=False, indent=2))
    else:
        _print_plan_human(items)
    return 1 if items else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
